package com.aiinterview.dto;

// Boilerplate starter code provided to the candidate for each language
public class StarterCode {
    private String javascript;
    private String python;
    private String java;
    private String cpp;

    public StarterCode() {}

    public StarterCode(String javascript, String python, String java, String cpp) {
        this.javascript = javascript;
        this.python = python;
        this.java = java;
        this.cpp = cpp;
    }

    public String getJavascript() { return javascript; }
    public void setJavascript(String javascript) { this.javascript = javascript; }

    public String getPython() { return python; }
    public void setPython(String python) { this.python = python; }

    public String getJava() { return java; }
    public void setJava(String java) { this.java = java; }

    public String getCpp() { return cpp; }
    public void setCpp(String cpp) { this.cpp = cpp; }
}
